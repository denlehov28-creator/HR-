// «Помощник»: обычный чат для повседневных задач — письма коллегам,
// проверка грамотности текста и текста на картинках.

import * as ai from "./ai.js";
import { loadBrand } from "./brand.js";
import { h, emptyKeyNotice } from "./ui.js";
import { brandContext } from "./prompts.js";
import { chatBox } from "./chat.js";

export const assistantSystem = (brand) => `Ты — внимательный помощник HR-специалиста и корректор русского языка.

Что ты делаешь:
- Пишешь короткие грамотные письма и сообщения коллегам по описанию: тема письма, обращение, суть в первом абзаце, вежливое завершение. Тон — деловой, но человеческий, без канцелярита. Если не сказано иное, давай один готовый вариант; по просьбе — 2–3 варианта разного тона.
- Проверяешь грамотность: орфография, пунктуация, согласование, стиль. Формат ответа при проверке:
  1) «Исправленный текст» — целиком;
  2) «Что исправлено» — список: было → стало и короткое объяснение правила (чтобы человек учился);
  3) если ошибок нет — так и скажи.
- Проверяешь текст на изображениях (макеты, поздравления, объявления, слайды): выпиши весь текст с картинки, найди опечатки, ошибки, лишние пробелы, неверные кавычки и тире, несогласованность, ошибки в датах и днях недели. Отметь, что хорошо бы поправить в подаче текста. Не оценивай и не меняй логотип.
- Помогаешь с короткими задачами: сократить, сделать вежливее, перевести на деловой язык, придумать тему письма.

Правила:
- Не выдумывай факты, даты и имена: неизвестное ставь в [квадратные скобки].
- Не повторяй персональные данные без нужды; напомни заменять их на [ФИО], если человек вставил паспортные данные, СНИЛС, сведения о здоровье.
- Отвечай коротко и по делу.${brandContext(brand)}`;

const STARTERS = [
  ["Письмо коллеге", "Напиши письмо коллеге: ", true],
  ["Письмо руководителю", "Напиши письмо руководителю: ", true],
  ["Проверить грамотность", "Проверь грамотность текста:\n\n", true],
  ["Проверить картинку", "Проверь текст на приложенной картинке на ошибки.", true],
  ["Сделать вежливее", "Перепиши вежливее, сохранив смысл:\n\n", true],
  ["Сократить", "Сократи текст в два раза, сохранив главное:\n\n", true],
  ["Ответ на жалобу", "Помоги ответить сотруднику на жалобу: ", true],
  ["Тема письма", "Придумай 3 варианта темы для письма: ", true],
];

export async function render(root) {
  const brand = await loadBrand();
  const chat = chatBox({
    storeKey: "assistant-history",
    system: async () => assistantSystem(brand),
    starters: STARTERS,
    placeholder: "Что нужно? Например: «напиши Ивану, что отчёт переносится на пятницу» или вставьте текст для проверки",
    thinking: "Пишу…",
    saveKind: "assistant",
    accept: "image/png,image/jpeg,image/webp,application/pdf,text/plain,.txt",
    fileHint: "Картинка или файл для проверки: ",
  });
  root.append(
    h("div", { class: "page-head" },
      h("h1", {}, "Помощник"),
      h("p", { class: "lead" }, "Письма коллегам, проверка грамотности текста и картинок, быстрые правки. Выберите действие или просто напишите, что нужно."),
    ),
    (await ai.hasKey()) ? "" : emptyKeyNotice(),
    chat.el,
  );
}
